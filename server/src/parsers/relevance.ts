/**
 * Скоринг: насколько заказ подходит веб-дизайнеру, который делает лендинги.
 * score >= 4 → попадает в ленту; isLanding → отдельный бейдж и фильтр.
 */
const LANDING = [/лендинг/i, /landing/i, /посадочн/i, /одностранич/i, /\bLP\b/, /лонгрид/i, /промо-?страниц/i, /квиз/i];

const STRONG: [RegExp, number][] = [
  [/веб-?дизайн|web-?design/i, 4],
  [/дизайн[а-я]*\s+(сайт|страниц|интерфейс|лендинг)/i, 4],
  [/(сайт|страниц)[а-я]*\s.{0,20}дизайн/i, 3],
  [/макет[а-я]*\s+(сайт|страниц|лендинг)/i, 4],
  [/редизайн/i, 3],
  [/tilda|тильд/i, 4],
  [/figma|фигм/i, 3],
  [/webflow|readymag|framer/i, 4],
  [/ui\s*\/?\s*ux|ux\s*\/?\s*ui|\bui\b|\bux\b/i, 2],
  [/прототип/i, 2],
  [/(сделать|создать|разработ|нужен|нужно|требуется).{0,25}сайт/i, 3],
  [/сайт.{0,15}(под ключ|визитк|компании|для)/i, 2],
  [/интернет-?магазин/i, 1],
  [/верстк|вёрстк/i, 1],
  [/главн[а-я]+\s+страниц/i, 2],
  [/wordpress|битрикс/i, 1],
];

/** Типичные посты-самопиар исполнителей и мусор */
const NEGATIVE: [RegExp, number][] = [
  [/#?резюме/i, -8],
  [/ищу (заказ|работ|клиент|проект)/i, -8],
  [/(возьму|беру) (заказ|проект)/i, -6],
  [/(выполню|сделаю|создам) (для вас|вам|ваш)/i, -6],
  [/мои работы|моё портфолио|мое портфолио|смотрите портфолио/i, -4],
  [/вакансия.{0,40}(офис|полный день|в штат)/i, -2],
  [/без опыта/i, -4],
  [/авито|wildberries|\bwb\b|ozon|озон|маркетплейс/i, -3],
  [/карточ[а-я]+ товар/i, -3],
  [/логотип/i, -1],
  [/курс(ы|ов)? (по|для)|обучени/i, -3],
  [/продвиж|\bseo\b|контекстн|таргет/i, -4],
  [/программист|backend|бэкенд|\bphp\b|1с|парсер|бот[а-я]* для/i, -2],
  [/в штат|полная занятость|оформлени[ея] по ТК/i, -3],
];

export function scoreLead(title: string, description: string) {
  const text = `${title}\n${description}`;
  const isLanding = LANDING.some((r) => r.test(text));
  let score = isLanding ? 6 : 0;
  for (const [r, w] of STRONG) if (r.test(text)) score += w;
  // в заголовке совпадения весят больше
  for (const [r, w] of STRONG) if (r.test(title)) score += Math.ceil(w / 2);
  for (const [r, w] of NEGATIVE) if (r.test(text)) score += w;
  return { score, isLanding: isLanding && score > 0 };
}

export const RELEVANT_THRESHOLD = 4;
